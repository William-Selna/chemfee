import type { Metadata } from "next";
import { brand } from "@/content/site";

/**
 * Canonical origin for the site. Set NEXT_PUBLIC_SITE_URL in .env.local
 * (or your host's dashboard) before deploying — canonicals, OG URLs, the
 * sitemap and robots.txt all derive from it.
 */
export const siteUrl = (
  process.env.NEXT_PUBLIC_SITE_URL ?? "https://www.chemfee.nl"
).replace(/\/$/, "");

export function absoluteUrl(path = "/") {
  const p = path.startsWith("/") ? path : `/${path}`;
  // The static export writes directory-style URLs (/coffee/index.html), so page
  // URLs carry a trailing slash. Asset paths with a file extension do not.
  const isFile = /\.[a-z0-9]+$/i.test(p);
  return `${siteUrl}${isFile || p.endsWith("/") ? p : `${p}/`}`;
}

/** The site-wide social card, a static file in /public. */
export const defaultOgImage = absoluteUrl("/opengraph-image.png");

type PageMetaInput = {
  title: string;
  description: string;
  path: string;
  /** Defaults to the site-wide OG image generated by app/opengraph-image.tsx */
  image?: string;
  type?: "website" | "article";
  publishedTime?: string;
  modifiedTime?: string;
  authors?: string[];
  noIndex?: boolean;
};

/**
 * Builds a complete, consistent metadata object for a page: canonical URL,
 * Open Graph, and Twitter card. Every page should go through this.
 */
export function pageMetadata({
  title,
  description,
  path,
  image = defaultOgImage,
  type = "website",
  publishedTime,
  modifiedTime,
  authors,
  noIndex,
}: PageMetaInput): Metadata {
  const url = absoluteUrl(path);
  // Setting `openGraph` on a page replaces the parent's, so the file-convention
  // image has to be re-attached explicitly rather than inherited.

  return {
    title,
    description,
    alternates: { canonical: url },
    robots: noIndex ? { index: false, follow: false } : undefined,
    openGraph: {
      title: `${title} — ${brand.name}`,
      description,
      url,
      siteName: brand.name,
      locale: "en_US",
      type,
      ...(image ? { images: [{ url: image, width: 1200, height: 630, alt: title }] } : {}),
      ...(type === "article"
        ? { publishedTime, modifiedTime, authors }
        : {}),
    },
    twitter: {
      card: "summary_large_image",
      title: `${title} — ${brand.name}`,
      description,
      ...(image ? { images: [image] } : {}),
    },
  };
}

export function formatDate(iso: string) {
  return new Date(`${iso}T00:00:00Z`).toLocaleDateString("en-US", {
    year: "numeric",
    month: "long",
    day: "numeric",
    timeZone: "UTC",
  });
}
